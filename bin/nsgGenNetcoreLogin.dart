        _options.ReviewLogins.FirstOrDefault(r => r.Code.Length > 0 &&
            (NormalizePhone(r.Login) == login || NormalizeEmail(r.Login) == login))?.Code;

    private bool IsReviewCode(string login, string code) =>
        ReviewCode(login) is { } c && FixedTimeEquals(c, code);

    public static string GenerateCode(int length)
    {
        // Цифры 1–9: ведущий ноль теряется при вводе в числовое поле.
        var chars = new char[Math.Clamp(length, 4, 12)];
        for (var i = 0; i < chars.Length; i++) chars[i] = (char)('1' + RandomNumberGenerator.GetInt32(9));
        return new string(chars);
    }

    private string HashCode(Guid requestId, string login, string code)
    {
        using var hmac = new HMACSHA256(Encoding.UTF8.GetBytes(_jwt.Secret));
        return Convert.ToHexString(hmac.ComputeHash(Encoding.UTF8.GetBytes($"{requestId:N}:{login}:{code}")));
    }

    public static string HashPassword(string password)
    {
        const int iterations = 100_000;
        var salt = RandomNumberGenerator.GetBytes(16);
        var hash = Rfc2898DeriveBytes.Pbkdf2(password, salt, iterations, HashAlgorithmName.SHA256, 32);
        return $"pbkdf2-sha256${iterations}${Convert.ToBase64String(salt)}${Convert.ToBase64String(hash)}";
    }

    public static bool VerifyPassword(string password, string? stored)
    {
        if (string.IsNullOrEmpty(password) || string.IsNullOrEmpty(stored)) return false;
        var parts = stored.Split('$');
        if (parts.Length != 4 || parts[0] != "pbkdf2-sha256" || !int.TryParse(parts[1], out var iterations)) return false;
        try
        {
            var salt = Convert.FromBase64String(parts[2]);
            var expected = Convert.FromBase64String(parts[3]);
            var actual = Rfc2898DeriveBytes.Pbkdf2(password, salt, iterations, HashAlgorithmName.SHA256, expected.Length);
            return CryptographicOperations.FixedTimeEquals(actual, expected);
        }
        catch (FormatException) { return false; }
    }

    private static bool FixedTimeEquals(string a, string b) =>
        CryptographicOperations.FixedTimeEquals(Encoding.UTF8.GetBytes(a), Encoding.UTF8.GetBytes(b));
}

