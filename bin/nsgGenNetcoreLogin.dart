    public static string NormalizePhone(string s) =>
        new(s.Where(c => !char.IsWhiteSpace(c) && c != '(' && c != ')' && c != '-').ToArray());

    public static string NormalizeEmail(string s) => s.Trim().ToLowerInvariant();

