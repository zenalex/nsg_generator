/// Вход по логину (телефон или почта) и файлы для netcore-эмита.
///
/// Включается ключом `loginAuth`. Повторяет контракт `Api/Auth/*`, которым
/// пользуются nsg_data и nsg_login, но хранит пользователей, сессии и коды в
/// базе: при двух экземплярах сервера на одной базе коды и отзыв сессий
/// должны быть видны обоим, а прежнее хранение в памяти этого не давало.
///
/// Файлы — MinIO (как в futbolista): `GetStream` перенаправляет на
/// подписанную ссылку.
///
/// Порождаемое (перезаписывается) — `<Generated>/Auth/*`,
/// `<Generated>/Controllers/NsgAuthController.cs`; рукописное (один раз) —
/// `Auth/NsgAuthHooks.cs`: что делать проекту после входа.
class NsgGenNetcoreLogin {
  static String _ns(NsgGenerator gen, String text) =>
      text.replaceAll('@@NS@@', gen.cSharpNamespace);

  /// Есть ли функция `GetStream`, которую сервер обслуживает сам.
  static bool hasFileStream(NsgGenerator gen) => gen.controllers
      .any((c) => c.functions.any((f) => isBuiltInGetStream(f.name, f.type)));

  static bool isBuiltInGetStream(String name, String type) =>
      name == 'GetStream' && (type == 'Binary' || type == 'Image');

  static Future<void> emitFiles(NsgGenerator gen) async {
    if (gen.loginAuth) {
      final authDir = '${gen.netcoreGeneratedPath}/Auth';
      await Directory(authDir).create(recursive: true);
      final files = {
        'NsgAuthModels.cs': emitModels(gen),
        'NsgAuthOptions.cs': emitOptions(gen),
        'NsgAuthService.cs': emitService(gen),
        'NsgAuthTokenHandler.cs': emitTokenHandler(gen),
        'NsgCodeDispatcher.cs': emitCodeDispatcher(gen),
        'NsgAuthHooks.Generated.cs': emitHooksGenerated(gen),
      };
      for (final e in files.entries) {
        await Misc.writeFileIfChanged('$authDir/${e.key}', e.value);
      }
      final ctrlDir = '${gen.netcoreGeneratedPath}/Controllers';
      await Directory(ctrlDir).create(recursive: true);
      await Misc.writeFileIfChanged(
          '$ctrlDir/NsgAuthController.cs', emitController(gen));
      final hooksDir = '${gen.netcoreOutputPath}/Auth';
      await Directory(hooksDir).create(recursive: true);
      final hooks = File('$hooksDir/NsgAuthHooks.cs');
      if (!await hooks.exists() || gen.forceOverwrite) {
        await Misc.writeFileIfChanged(hooks.path, emitHooksCustom(gen));
      }
    }
    if (hasFileStream(gen)) {
      final configsDir = '${gen.netcoreGeneratedPath}/Configurations';
      await Directory(configsDir).create(recursive: true);
      await Misc.writeFileIfChanged(
          '$configsDir/NsgFileStore.cs', emitFileStore(gen));
    }
  }

