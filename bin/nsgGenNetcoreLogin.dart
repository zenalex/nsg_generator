/// <summary>Тело запроса входа (NsgLoginModel клиента).</summary>
public sealed record NsgLoginRequest(
    string Login, bool IsEmail, string SecurityCode, bool Register, string? NewPassword, string? DeviceId)
{
    public static NsgLoginRequest Parse(JsonElement body)
    {
        string Str(string name) =>
            body.ValueKind == JsonValueKind.Object && body.TryGetProperty(name, out var v) && v.ValueKind == JsonValueKind.String
                ? v.GetString() ?? "" : "";
        bool Bool(string name) =>
            body.ValueKind == JsonValueKind.Object && body.TryGetProperty(name, out var v) &&
            (v.ValueKind == JsonValueKind.True || (v.ValueKind == JsonValueKind.String && bool.TryParse(v.GetString(), out var b) && b));
        var isEmail = string.Equals(Str("loginType"), "email", StringComparison.OrdinalIgnoreCase);
        var login = isEmail ? NsgAuthService.NormalizeEmail(Str("phoneNumber")) : NsgAuthService.NormalizePhone(Str("phoneNumber"));
        var newPassword = Str("newPassword");
        if (newPassword.Length == 0) newPassword = Str("password");
        return new NsgLoginRequest(login, isEmail, Str("securityCode"), Bool("register"),
            newPassword.Length == 0 ? null : newPassword, Str("deviceId") is { Length: > 0 } d ? d : null);
    }
}

/// <summary>Что известно из токена без обращения к базе.</summary>
public sealed record NsgTokenInfo(Guid SessionId, Guid? UserId, string Token);

public sealed class NsgAuthService
{
    public const string SessionClaim = "sid";
    public const string UserClaim = "sub";
    public const string RoleClaim = "role";

    private readonly AppDbContext _db;
    private readonly NsgJwtOptions _jwt;
    private readonly NsgAuthOptions _options;
    private readonly NsgCodeDispatcher _sender;
    private readonly NsgAuthHooks _hooks;
    private readonly ILogger<NsgAuthService> _log;

    public NsgAuthService(AppDbContext db, IOptions<NsgJwtOptions> jwt, IOptions<NsgAuthOptions> options,
        NsgCodeDispatcher sender, NsgAuthHooks hooks, ILogger<NsgAuthService> log)
    {
        _db = db; _jwt = jwt.Value; _options = options.Value; _sender = sender; _hooks = hooks; _log = log;
    }

    // ---- токены ----

    public string IssueAnonymous() =>
        Issue(new List<Claim> { new(SessionClaim, Guid.NewGuid().ToString("D")), new(RoleClaim, UserRoles.Anonymous) },
            DateTime.UtcNow.AddDays(Math.Max(1, _jwt.LifetimeDays)));

    private string IssueForSession(NsgAuthSession session) =>
        Issue(new List<Claim>
        {
            new(SessionClaim, session.Id.ToString("D")),
            new(UserClaim, session.UserId.ToString("D")),
            new(RoleClaim, UserRoles.User),
        }, DateTime.UtcNow.AddDays(Math.Max(1, _options.SessionLifetimeDays)));

    private string Issue(IEnumerable<Claim> claims, DateTime expires)
    {
        var key = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(_jwt.Secret));
        var token = new JwtSecurityToken(_jwt.Issuer, _jwt.Audience, claims, DateTime.UtcNow, expires,
            new SigningCredentials(key, SecurityAlgorithms.HmacSha256));
        return new JwtSecurityTokenHandler().WriteToken(token);
    }

    /// <summary>Сырой заголовок без `Bearer `: прежний сервер выдавал токен с
    /// приставкой, и клиент мог её сохранить.</summary>
    public static string StripBearer(string? raw)
    {
        var t = (raw ?? "").Trim();
        return t.StartsWith("Bearer ", StringComparison.OrdinalIgnoreCase) ? t[7..].Trim() : t;
    }

    private ClaimsPrincipal? Validate(string token)
    {
        if (token.Length == 0) return null;
        var handler = new JwtSecurityTokenHandler { MapInboundClaims = false };
        var parameters = new TokenValidationParameters
        {
            ValidIssuer = _jwt.Issuer,
            ValidAudience = _jwt.Audience,
            IssuerSigningKey = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(_jwt.Secret)),
            ValidateIssuer = true,
            ValidateAudience = true,
            ValidateLifetime = true,
            ValidateIssuerSigningKey = true,
            ClockSkew = TimeSpan.FromMinutes(2),
            NameClaimType = UserClaim,
            RoleClaimType = RoleClaim,
        };
        try { return handler.ValidateToken(token, parameters, out _); }
        catch (Exception) { return null; }
    }

    public NsgTokenInfo? ReadToken(string? raw)
    {
        var token = StripBearer(raw);
        var principal = Validate(token);
        if (principal is null || !Guid.TryParse(principal.FindFirst(SessionClaim)?.Value, out var sid)) return null;
        Guid? userId = Guid.TryParse(principal.FindFirst(UserClaim)?.Value, out var u) ? u : null;
        return new NsgTokenInfo(sid, userId, token);
    }

    /// <summary>Проверка токена запроса. Токен пользователя действителен,
    /// только пока его сессия есть в базе и не отозвана.</summary>
    public async Task<ClaimsPrincipal?> AuthenticateAsync(string? raw, CancellationToken ct)
    {
        var token = StripBearer(raw);
        var principal = Validate(token);
        if (principal is null || !Guid.TryParse(principal.FindFirst(SessionClaim)?.Value, out var sid)) return null;
        if (!principal.IsInRole(UserRoles.User)) return principal;
        var session = await _db.NsgAuthSessions.FirstOrDefaultAsync(s => s.Id == sid, ct);
        if (session is null || session.RevokedAt is not null) return null;
        var now = DateTime.UtcNow;
        if (now - session.LastUsedAt > TimeSpan.FromHours(1))
        {
            session.LastUsedAt = now;
            await _db.SaveChangesAsync(ct);
        }
        return principal;
    }

    // ---- вход ----

    public async Task<NsgAuthResponse> CheckTokenAsync(string? raw, string? deviceId, CancellationToken ct)
    {
        var info = ReadToken(raw);
        var session = info?.UserId is null ? null
            : await _db.NsgAuthSessions.FirstOrDefaultAsync(s => s.Id == info.SessionId && s.RevokedAt == null, ct);
        if (session is null) return NsgAuthResponse.Error(NsgAuthErrors.InvalidToken, "Wrong code");
        session.LastUsedAt = DateTime.UtcNow;
        if (!string.IsNullOrEmpty(deviceId)) session.DeviceId = deviceId;
        await _db.SaveChangesAsync(ct);
        return new NsgAuthResponse { Token = info!.Token, IsAnonymous = false };
    }

    /// <summary>`PhoneLoginRequestSMS`: вход по паролю (`register: false`) или
    /// отправка кода (`register: true`) — так ведёт себя клиент.</summary>
    public async Task<NsgAuthResponse> RequestAsync(NsgLoginRequest login, string? raw, CancellationToken ct)
    {
        if (login.Login.Length == 0) return NsgAuthResponse.Error(NsgAuthErrors.WrongLogin, "Не указан телефон или почта");
        var info = ReadToken(raw);
        var requestToken = info?.Token ?? IssueAnonymous();
        var requestId = info?.SessionId ?? ReadToken(requestToken)!.SessionId;
        var now = DateTime.UtcNow;

        if (!login.Register)
        {
            var user = await FindUserAsync(login.Login, login.IsEmail, ct);
            var ok = user is not null &&
                     (VerifyPassword(login.SecurityCode, user.PasswordHash) || IsReviewCode(login.Login, login.SecurityCode));
            if (!ok) return NsgAuthResponse.Error(NsgAuthErrors.WrongLogin, "Неверный логин или пароль");
            return await LoginAsync(user!, isNewUser: false, login.DeviceId, ct);
        }

        await _db.NsgAuthCodes.Where(c => c.ExpiresAt < now.AddDays(-1)).ExecuteDeleteAsync(ct);
        var previous = await _db.NsgAuthCodes.Where(c => c.RequestId == requestId)
            .OrderByDescending(c => c.CreatedAt).FirstOrDefaultAsync(ct);
        if (previous is not null && previous.Login == login.Login && previous.ResendAfter > now)
        {
            var wait = Math.Ceiling((previous.ResendAfter - now).TotalSeconds);
            return NsgAuthResponse.Error(NsgAuthErrors.WrongCode, $"Повторная отправка кода через {wait} с", 0, wait);
        }

        var review = ReviewCode(login.Login);
        var code = review ?? GenerateCode(_options.CodeLength);
        var resend = login.IsEmail ? _options.EmailResendSeconds : _options.SmsResendSeconds;
        if (review is null)
        {
            try { await _sender.SendAsync(login.IsEmail, login.Login, code, ct); }
            catch (Exception error)
            {
                _log.LogError(error, "Не удалось отправить код на {Login}", login.Login);
                return NsgAuthResponse.Error(NsgAuthErrors.SendFailed, "Не удалось отправить код");
            }
        }
        await _db.NsgAuthCodes.Where(c => c.RequestId == requestId).ExecuteDeleteAsync(ct);
        _db.NsgAuthCodes.Add(new NsgAuthCode
        {
            Id = Guid.NewGuid(),
            RequestId = requestId,
            Login = login.Login,
            IsEmail = login.IsEmail,
            CodeHash = HashCode(requestId, login.Login, code),
            CreatedAt = now,
            ExpiresAt = now.AddSeconds(_options.CodeLifetimeSeconds),
            ResendAfter = now.AddSeconds(resend),
        });
        await _db.SaveChangesAsync(ct);
        // isAnonymous: false — как у прежнего сервера (поле опускалось и
        // читалось клиентом как false); клиент сохраняет этот токен и с ним
        // же присылает код.
        return new NsgAuthResponse
        {
            Token = requestToken,
            IsAnonymous = false,
            SecondsRemaining = _options.CodeLifetimeSeconds,
            SecondsBeforeRepeat = resend,
        };
    }

    /// <summary>`PhoneLogin`: код, отправленный по запросу с этим же токеном.
    /// Вход выполняется на адрес, куда ушёл код, а не на присланный сейчас:
    /// иначе код, полученный на свой телефон, открывал бы чужой.</summary>
    public async Task<NsgAuthResponse> LoginByCodeAsync(NsgLoginRequest login, string? raw, CancellationToken ct)
    {
        var info = ReadToken(raw);
        if (info is null) return NsgAuthResponse.Error(NsgAuthErrors.NoCode, "Код не запрашивался");
        var now = DateTime.UtcNow;
        var code = await _db.NsgAuthCodes.Where(c => c.RequestId == info.SessionId)
            .OrderByDescending(c => c.CreatedAt).FirstOrDefaultAsync(ct);
        if (code is null) return NsgAuthResponse.Error(NsgAuthErrors.NoCode, "Код не запрашивался");
        if (code.ExpiresAt <= now)
        {
            _db.NsgAuthCodes.Remove(code);
            await _db.SaveChangesAsync(ct);
            return NsgAuthResponse.Error(NsgAuthErrors.CodeExpired, "Срок действия кода истёк");
        }
        if (!FixedTimeEquals(code.CodeHash, HashCode(code.RequestId, code.Login, login.SecurityCode)))
        {
            code.Attempts++;
            if (code.Attempts >= _options.MaxAttempts)
            {
                _db.NsgAuthCodes.Remove(code);
                await _db.SaveChangesAsync(ct);
                return NsgAuthResponse.Error(NsgAuthErrors.AttemptsExhausted, "Попытки ввода кода исчерпаны");
            }
            await _db.SaveChangesAsync(ct);
            return NsgAuthResponse.Error(NsgAuthErrors.WrongCode, "Неверный код",
                Math.Ceiling((code.ExpiresAt - now).TotalSeconds),
                Math.Max(0, Math.Ceiling((code.ResendAfter - now).TotalSeconds)));
        }

        _db.NsgAuthCodes.Remove(code);
        var user = await FindUserAsync(code.Login, code.IsEmail, ct);
        var isNew = user is null;
        if (user is null)
        {
            user = new NsgAuthUser { Id = Guid.NewGuid(), RegisteredAt = now };
            if (code.IsEmail) user.Email = code.Login; else user.Phone = code.Login;
