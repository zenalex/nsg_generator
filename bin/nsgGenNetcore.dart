  /// Неизменная часть `NsgTableParts` — не зависит от схемы.
  static const String _tablePartsRuntime = r'''

    /// <summary>`docState` строки, помеченной клиентом на удаление.</summary>
    private const int DeletedDocState = 2;
    private const string RowNumberProperty = "RowNumber";

    public static IReadOnlyList<NsgTablePart> Of(Type ownerType) =>
        ByOwner.TryGetValue(ownerType, out var parts) ? parts : Array.Empty<NsgTablePart>();

    public static IReadOnlyCollection<string> AllWireNames(Type ownerType) =>
        Of(ownerType).Select(p => p.WireName).ToArray();

    /// <summary>Разделяет ReadReferences: пути, начинающиеся с табличной части,
    /// превращаются в её имя (строки едут внутри владельца, а их ссылки клиент
    /// дочитывает сам), остальные возвращаются как есть.</summary>
    public static (HashSet<string> Tables, string[]? References) SplitReadReferences(Type ownerType, string[]? readReferences)
    {
        var tables = new HashSet<string>();
        if (readReferences is null) return (tables, null);
        var parts = Of(ownerType);
        var rest = new List<string>();
        foreach (var path in readReferences)
        {
            if (string.IsNullOrEmpty(path)) continue;
            var head = path.Split('.')[0];
            var part = parts.FirstOrDefault(p => p.WireName == head);
            if (part is null) rest.Add(path);
            else tables.Add(part.WireName);
        }
        return (tables, rest.ToArray());
    }

    public static IQueryable<T> Include<T>(IQueryable<T> query, IReadOnlyCollection<string> wireNames) where T : class
    {
        var any = false;
        foreach (var part in Of(typeof(T)))
        {
            if (!wireNames.Contains(part.WireName)) continue;
            query = query.Include(part.Property);
            any = true;
        }
        // Несколько коллекций одним запросом дают декартово произведение строк.
        return any ? query.AsSplitQuery() : query;
    }

    public static IQueryable<T> IncludeAll<T>(IQueryable<T> query) where T : class =>
        Include(query, AllWireNames(typeof(T)));

    /// <summary>Объект в формате обмена вместе с запрошенными табличными частями.</summary>
    public static Dictionary<string, object?> ToWireDict(object entity, IReadOnlyCollection<string> wireNames)
    {
        var dict = NsgWireSerializer.ToWireDict(entity);
        var type = entity.GetType();
        foreach (var part in Of(type))
        {
            if (!wireNames.Contains(part.WireName)) continue;
            var rows = (IEnumerable?)type.GetProperty(part.Property)!.GetValue(entity);
            var rowNumber = part.RowType.GetProperty(RowNumberProperty)!;
            dict[part.WireName] = rows is null
                ? new List<Dictionary<string, object?>>()
                : rows.Cast<object>()
                    .OrderBy(r => (int)rowNumber.GetValue(r)!)
                    .Select(NsgWireSerializer.ToWireDict)
                    .ToList();
        }
        return dict;
    }

    /// <summary>Переносит присланные табличные части на отслеживаемого владельца.
    /// Владелец должен быть загружен со всеми табличными частями
    /// (<see cref="IncludeAll{T}"/>) или быть новым.</summary>
    /// <exception cref="NsgWireFormatException">Негодные строки — отказ клиенту.</exception>
    public static void Apply(DbContext db, object owner, JsonElement el)
    {
        if (el.ValueKind != JsonValueKind.Object) return;
        var parts = Of(owner.GetType());
        if (parts.Count == 0) return;
        var newTableLogic = el.TryGetProperty("newTableLogic", out var ntl) && ntl.ValueKind == JsonValueKind.True;
        var ownerId = (Guid)db.Entry(owner).Metadata.FindPrimaryKey()!.Properties[0].PropertyInfo!.GetValue(owner)!;
        foreach (var part in parts)
        {
            if (!el.TryGetProperty(part.WireName, out var rowsEl)) continue;
            if (rowsEl.ValueKind == JsonValueKind.Null) continue;
            if (rowsEl.ValueKind != JsonValueKind.Array)
                throw new NsgWireFormatException($"табличная часть «{part.WireName}»: ожидался массив строк, получено {rowsEl.ValueKind}");
            ApplyPart(db, owner, ownerId, part, rowsEl, newTableLogic);
        }
    }

    private static void ApplyPart(DbContext db, object owner, Guid ownerId, NsgTablePart part, JsonElement rowsEl, bool newTableLogic)
    {
        var rowEntity = db.Model.FindEntityType(part.RowType)
            ?? throw new InvalidOperationException($"No EF entity for {part.RowType.Name}");
        var rowPk = rowEntity.FindPrimaryKey()!.Properties[0].PropertyInfo!;
        var pkWire = TypeFieldMapRegistry.ByType[part.RowType].CSharpToWire[rowPk.Name];
        var rowNumber = part.RowType.GetProperty(RowNumberProperty)!;
        var ownerFk = part.OwnerFkProperty is null ? null : part.RowType.GetProperty(part.OwnerFkProperty);

        var collection = owner.GetType().GetProperty(part.Property)!.GetValue(owner)
            ?? throw new InvalidOperationException($"{owner.GetType().Name}.{part.Property} is null");
        var collectionApi = typeof(ICollection<>).MakeGenericType(part.RowType);
        var add = collectionApi.GetMethod("Add")!;
        var remove = collectionApi.GetMethod("Remove")!;

        var existingRows = ((IEnumerable)collection).Cast<object>().ToList();
        var byId = existingRows.ToDictionary(r => (Guid)rowPk.GetValue(r)!);

        // Разбор присланного: идентификатор и пометка удаления каждой строки.
        var incoming = new List<(JsonElement El, Guid Id, bool Delete)>();
        var seen = new HashSet<Guid>();
        foreach (var rowEl in rowsEl.EnumerateArray())
        {
            if (rowEl.ValueKind != JsonValueKind.Object)
                throw new NsgWireFormatException($"табличная часть «{part.WireName}»: строка должна быть объектом, получено {rowEl.ValueKind}");
            var id = Guid.Empty;
            if (rowEl.TryGetProperty(pkWire, out var idEl) && idEl.ValueKind == JsonValueKind.String
                && !string.IsNullOrEmpty(idEl.GetString()))
            {
                if (!Guid.TryParse(idEl.GetString(), out id))
                    throw new NsgWireFormatException($"табличная часть «{part.WireName}»: «{idEl.GetString()}» не является идентификатором строки");
            }
            if (id != Guid.Empty && !seen.Add(id))
                throw new NsgWireFormatException($"табличная часть «{part.WireName}»: строка {id} прислана дважды");
            var delete = newTableLogic
                && rowEl.TryGetProperty("docState", out var ds)
                && ds.ValueKind == JsonValueKind.Number
                && ds.TryGetInt32(out var state) && state == DeletedDocState;
            incoming.Add((rowEl, id, delete));
        }

        void RemoveRow(object row)
        {
            remove.Invoke(collection, new[] { row });
            db.Remove(row);
        }

        // Прежняя логика: присланный массив — полный состав таблицы.
        if (!newTableLogic)
        {
            foreach (var row in existingRows)
                if (!seen.Contains((Guid)rowPk.GetValue(row)!)) RemoveRow(row);
        }

        // Порядок присланного переносится, только если прислана вся таблица.
        // Иначе (выборочная досылка) прежние строки остаются на своих местах,
        // а новые встают в конец.
        var reorder = !newTableLogic || existingRows.All(r => seen.Contains((Guid)rowPk.GetValue(r)!));
        var next = reorder ? 0 : existingRows.Select(r => (int)rowNumber.GetValue(r)!).DefaultIfEmpty(-1).Max() + 1;

        foreach (var (rowEl, id, delete) in incoming)
        {
            if (delete)
            {
                if (byId.TryGetValue(id, out var gone)) RemoveRow(gone);
                continue;
            }

            object fresh;
            try
            {
                fresh = typeof(NsgEntityMapper).GetMethod(nameof(NsgEntityMapper.MapFromWire))!
                    .MakeGenericMethod(part.RowType)
                    .Invoke(null, new object[] { rowEl, db.Model })!;
            }
            catch (TargetInvocationException error) when (error.InnerException is NsgWireFormatException inner)
            {
                throw new NsgWireFormatException($"табличная часть «{part.WireName}»: {inner.Message}");
            }

            if (byId.TryGetValue(id, out var row))
            {
                var keptNumber = (int)rowNumber.GetValue(row)!;
                db.Entry(row).CurrentValues.SetValues(fresh);
                NsgSaveHooks.CopyTransient(fresh, row);
                rowNumber.SetValue(row, reorder ? next++ : keptNumber);
            }
            else
            {
