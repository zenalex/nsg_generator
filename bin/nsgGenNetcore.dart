  /// Generated half of <T>Controller. Public для unit-тестов.
  static String emitControllerGenerated(NsgGenerator gen,
      NsgGenController controller, NsgGenMethod method, String dsName) {
    final ns = gen.cSharpNamespace;
    final di = method.genDataItem;
    final t = di.typeName;
    final route = '${controller.apiPrefix}/${method.apiPrefix}';
    // У владельца табличных частей чтение и запись идут через NsgTableParts;
    // вывод для остальных типов не меняется.
    final hasTables = tablePartsOf(gen, di).isNotEmpty;

    final sb = StringBuffer();
    sb.writeln('// <auto-generated>');
    sb.writeln(
        '//   This file is generated by nsg_generator. Manual edits will be overwritten.');
    sb.writeln('//   For custom business logic edit $t' 'Controller.Custom.cs.');
    sb.writeln('// </auto-generated>');
    sb.writeln('#nullable enable');
    sb.writeln('using System;');
    sb.writeln('using System.Collections.Generic;');
    sb.writeln('using System.Linq;');
    sb.writeln('using System.Text.Json;');
    sb.writeln('using System.Threading.Tasks;');
    sb.writeln('using Microsoft.AspNetCore.Authorization;');
    sb.writeln('using Microsoft.AspNetCore.Mvc;');
    sb.writeln('using Microsoft.EntityFrameworkCore;');
    sb.writeln('using $ns.Configurations;');
    sb.writeln('using $ns.Models;');
    sb.writeln('using $ns.Wire;');
    sb.writeln();
    sb.writeln('namespace $ns.Controllers;');
    sb.writeln();
    sb.writeln('// TASK06 §6.4 soft-cut: контроллер пока использует static `NsgCompareTranslator.Apply`');
    sb.writeln('// (legacy facade). Hard-cut на конструктор-injection `INsgCompareTranslator` — TASK07+.');
    sb.writeln('#pragma warning disable CS0618');
    sb.writeln();
    sb.writeln('[ApiController]');
    sb.writeln('[Route("$route")]');
    sb.writeln('public partial class ${t}Controller : ControllerBase');
    sb.writeln('{');
    sb.writeln('    private readonly AppDbContext _db;');
    sb.writeln('    public ${t}Controller(AppDbContext db) { _db = db; }');
    sb.writeln();

    // TASK06 §6.3 (d1) — compute effective authorize level per action (di > method).
    // Default 'none' → no attribute. Mirror upstream nsgGenMethod.dart convention.
    String? authAttr(String level) {
      if (level == 'anonymous') return '[Authorize]';
      if (level == 'user') return '[Authorize(Roles = UserRoles.User)]';
      if (level == 'admin') return '[Authorize(Roles = UserRoles.Admin)]';
      return null;
    }
    final effectiveAuthorize = di.authorize != 'none' ? di.authorize : method.authorize;
    final effGet    = method.authorizeGet.isNotEmpty    ? method.authorizeGet    : effectiveAuthorize;
    final effPost   = method.authorizePost.isNotEmpty   ? method.authorizePost   : effectiveAuthorize;
    final effDelete = method.authorizeDelete.isNotEmpty ? method.authorizeDelete : effectiveAuthorize;

    // Read
    if (method.allowGetter) {
      sb.writeln('    /// <summary>POST $route — read with NsgDataRequestParams body.</summary>');
      final attr = authAttr(effGet);
      if (attr != null) sb.writeln('    $attr');
      sb.writeln('    [HttpPost]');
      sb.writeln(
          '    public async Task<ActionResult<List<Dictionary<string, object?>>>> Read([FromBody] JsonElement body)');
      sb.writeln('    {');
      sb.writeln(
          '        var req = body.ValueKind == JsonValueKind.Object ? NsgWireDeserializer.ParseRequest(body) : new NsgRequestDto(null, null, null, null, null, null, null, false, null, null, null);');
      sb.writeln('        IQueryable<$t> query = _db.$dsName.AsNoTracking();');
      // Видимость — первой: до фильтра клиента, сортировки и Top, иначе
      // страница из Top объектов после фильтра оказалась бы неполной.
      sb.writeln('        query = NsgReadHooks.Filter(HttpContext, req.Parameters, query);');
      sb.writeln('        CustomizeReadQuery(ref query);');
      sb.writeln('        // TASK05 §5.3-5.6: apply NsgCompare (+ dot-path 5.6.1), ReadReferences');
      sb.writeln('        // (Include via 5.6.2), Sorting (with dot-path 5.6.3), Top.');
      sb.writeln('        query = NsgCompareTranslator.Apply(query, req.Compare, _db.Model);');
      if (hasTables) {
        sb.writeln('        // Табличные части едут строками внутри объекта; пути через них');
        sb.writeln('        // («files.authorId») сводятся к самой части — ссылки строк клиент дочитывает сам.');
        sb.writeln('        var (tables, references) = NsgTableParts.SplitReadReferences(typeof($t), NsgReadHooks.TablePartReferences<$t>(req.ReadReferences));');
        sb.writeln('        query = NsgReadReferencesApplier.Apply(query, references, _db.Model);');
        sb.writeln('        query = NsgTableParts.Include(query, tables);');
      } else {
        sb.writeln('        query = NsgReadReferencesApplier.Apply(query, NsgReadHooks.TablePartReferences<$t>(req.ReadReferences), _db.Model);');
      }
      // Сортировку по полю вне базы SQL не выполнит: тогда она и Top — в памяти,
      // после того как обработчики чтения заполнили поля.
      sb.writeln('        var sortInMemory = NsgReadHooks.SortsByTransient<$t>(req.Sorting);');
      sb.writeln('        if (!sortInMemory) query = NsgSortingApplier.Apply(query, req.Sorting, _db.Model);');
      sb.writeln('        if (!sortInMemory && req.Top is int top && top > 0) query = query.Take(top);');
      sb.writeln('        var items = await query.ToListAsync();');
      sb.writeln('        await NsgReadHooks.AfterReadAsync(HttpContext, req.Parameters, items);');
      sb.writeln('        if (sortInMemory)');
      sb.writeln('        {');
      sb.writeln('            NsgReadHooks.SortInMemory(items, req.Sorting);');
      sb.writeln('            if (req.Top is int memTop && memTop > 0 && items.Count > memTop) items.RemoveRange(memTop, items.Count - memTop);');
      sb.writeln('        }');
      if (hasTables) {
        sb.writeln('        return Ok(items.Select(x => NsgTableParts.ToWireDict(x, tables)).ToList());');
      } else {
        sb.writeln('        return Ok(items.Select(NsgWireSerializer.ToWireDict).ToList());');
      }
      sb.writeln('    }');
      sb.writeln();
    }

    // Post
    if (method.allowPost) {
      sb.writeln(method.postMode == 'insert-only'
          ? '    /// <summary>POST $route/Post — insert array of entities; existing id with different content is a conflict.</summary>'
          : '    /// <summary>POST $route/Post — upsert array of entities.</summary>');
      final attr = authAttr(effPost);
      if (attr != null) sb.writeln('    $attr');
      sb.writeln('    [HttpPost("Post")]');
      sb.writeln(
          '    public async Task<ActionResult<Dictionary<string, List<Dictionary<string, object?>>>>> PostItems([FromBody] JsonElement body)');
      sb.writeln('    {');
      sb.writeln(
          '        if (body.ValueKind != JsonValueKind.Array) return BadRequest("expected array");');
      sb.writeln('        var saved = new List<$t>();');
      sb.writeln('        foreach (var el in body.EnumerateArray())');
      sb.writeln('        {');
      // Негодное значение — отказ клиенту с указанием поля, а не 500:
      // это ошибка присланных данных, а не сбой сервера.
      sb.writeln('            $t fresh;');
      sb.writeln('            try { fresh = NsgEntityMapper.MapFromWire<$t>(el, _db.Model); }');
      sb.writeln('            catch (NsgWireFormatException error)');
      sb.writeln('            {');
      sb.writeln('                return BadRequest(new { error = "wire_format", reason = error.Message });');
      sb.writeln('            }');
      if (hasTables) {
        // Владелец грузится вместе со строками: без них не отличить
        // изменённую строку от новой и не найти удаляемые.
        sb.writeln('            var existing = await NsgTableParts.IncludeAll(_db.$dsName).FirstOrDefaultAsync(x => x.Id == fresh.Id);');
      } else {
        sb.writeln('            var existing = await _db.$dsName.FindAsync(fresh.Id);');
      }
      sb.writeln('            if (existing is null)');
      sb.writeln('            {');
      sb.writeln('                _db.$dsName.Add(fresh);');
      if (hasTables) _writeApplyTables(sb, 'fresh');
      sb.writeln('                saved.Add(fresh);');
      sb.writeln('            }');
      sb.writeln('            else');
      sb.writeln('            {');
      if (method.postMode == 'insert-only') {
        // Повтор с тем же содержимым — успех (идемпотентность повторной
        // отправки). С другим содержимым — конфликт: тихая перезапись
        // уничтожила бы единственный признак сбоя клиента или порчи данных.
        sb.writeln('                if (!NsgWireComparer.SameContent(');
        sb.writeln('                        NsgWireSerializer.ToWireDict(existing),');
        sb.writeln('                        NsgWireSerializer.ToWireDict(fresh)))');
        sb.writeln('                {');
        sb.writeln('                    OnPostConflict(fresh, existing);');
        sb.writeln('                    return Conflict(new { error = "content_mismatch", id = fresh.Id.ToString() });');
        sb.writeln('                }');
        sb.writeln('                saved.Add(existing);');
      } else {
        sb.writeln('                _db.Entry(existing).CurrentValues.SetValues(fresh);');
        if (hasTransientFields(method.genDataItem)) {
          // SetValues переносит только колонки базы, поля вне базы — отдельно.
          sb.writeln('                NsgSaveHooks.CopyTransient(fresh, existing);');
        }
        if (hasTables) _writeApplyTables(sb, 'existing');
        sb.writeln('                saved.Add(existing);');
      }
      sb.writeln('            }');
      sb.writeln('        }');
      sb.writeln('        OnBeforeSave(saved);');
      sb.writeln('        try { await NsgSaveHooks.BeforeSaveAsync(HttpContext, saved); }');
      sb.writeln('        catch (NsgRejectedException rejected) { return BadRequest(new { error = "rejected", message = rejected.Message }); }');
      sb.writeln('        await _db.SaveChangesAsync();');
      if (hasTables) {
        // Клиент заменяет объект ответом: без строк в ответе табличная часть
        // на экране опустела бы сразу после сохранения.
        sb.writeln('        var tables = NsgTableParts.AllWireNames(typeof($t));');
        sb.writeln('        return Ok(NsgPostResults(saved.Select(x => NsgTableParts.ToWireDict(x, tables))));');
      } else {
        sb.writeln('        return Ok(NsgPostResults(saved.Select(NsgWireSerializer.ToWireDict)));');
      }
      sb.writeln('    }');
      sb.writeln();
    }

    // Create: nsg_data (createOnServer) запрашивает новый объект у сервера —
    // POST <route>/Create. Ответ — объект с новым идентификатором и значениями
    // по умолчанию; в базу ничего не пишется (это делает Post).
    if (method.allowCreate) {
      sb.writeln('    /// <summary>POST $route/Create — новый объект для заполнения (не записывается).</summary>');
      final attr = authAttr(effPost);
      if (attr != null) sb.writeln('    $attr');
      sb.writeln('    [HttpPost("Create")]');
      sb.writeln('    public ActionResult<Dictionary<string, List<Dictionary<string, object?>>>> CreateItem()');
      sb.writeln('    {');
      sb.writeln('        var item = new $t { Id = Guid.NewGuid() };');
      sb.writeln('        OnCreate(item);');
      sb.writeln('        return Ok(new Dictionary<string, List<Dictionary<string, object?>>> { ["results"] = [NsgWireSerializer.ToWireDict(item)] });');
      sb.writeln('    }');
      sb.writeln();
    }

    // Delete
    if (method.allowDelete) {
      sb.writeln('    /// <summary>POST $route/Delete — delete array by id.</summary>');
      final attr = authAttr(effDelete);
      if (attr != null) sb.writeln('    $attr');
      sb.writeln('    [HttpPost("Delete")]');
      sb.writeln(
          '    public async Task<ActionResult> DeleteItems([FromBody] JsonElement body)');
      sb.writeln('    {');
      sb.writeln(
          '        if (body.ValueKind != JsonValueKind.Array) return BadRequest("expected array");');
      sb.writeln('        var ids = new List<Guid>();');
      sb.writeln('        foreach (var el in body.EnumerateArray())');
      sb.writeln('        {');
      sb.writeln('            if (el.TryGetProperty("id", out var idEl) && idEl.ValueKind == JsonValueKind.String && Guid.TryParse(idEl.GetString(), out var g))');
      sb.writeln('                ids.Add(g);');
      sb.writeln('        }');
      sb.writeln('        if (ids.Count == 0) return Ok();');
      sb.writeln('        var entities = await _db.$dsName.Where(x => ids.Contains(x.Id)).ToListAsync();');
      sb.writeln('        OnBeforeDelete(entities);');
      sb.writeln('        try { await NsgSaveHooks.BeforeDeleteAsync(HttpContext, entities); }');
      sb.writeln('        catch (NsgRejectedException rejected) { return BadRequest(new { error = "rejected", message = rejected.Message }); }');
      sb.writeln('        _db.$dsName.RemoveRange(entities);');
      sb.writeln('        await _db.SaveChangesAsync();');
      sb.writeln('        return Ok();');
      sb.writeln('    }');
      sb.writeln();
    }

    // 5.6.3: ApplySorting helper удалён из контроллера, заменён на
    // NsgSortingApplier (Wire-helper, разделяемый между всеми контроллерами).

    if (method.allowPost) {
      // Ответ на запись — `{"results": [...]}`: nsg_data (NsgDataPost) разбирает его
      // через loadDataAndReferences(Map), простой список ронял клиент после записи.
      sb.writeln('    private static Dictionary<string, List<Dictionary<string, object?>>> NsgPostResults(');
      sb.writeln('        IEnumerable<Dictionary<string, object?>> items) => new() { ["results"] = items.ToList() };');
      sb.writeln();
    }

    // Partial hooks
    sb.writeln('    // ---- Hooks for $t' 'Controller.Custom.cs (one-shot partial) ----');
    sb.writeln('    partial void CustomizeReadQuery(ref IQueryable<$t> query);');
    sb.writeln('    partial void OnBeforeSave(List<$t> items);');
    sb.writeln('    partial void OnBeforeDelete(List<$t> items);');
    if (method.allowCreate) sb.writeln('    partial void OnCreate($t item);');
    if (method.postMode == 'insert-only') {
      sb.writeln('    partial void OnPostConflict($t incoming, $t existing);');
    }
    sb.writeln('}');
    return sb.toString();
  }

