  /// Табличные части владельца: поле `List<Row>` и сведения о строке.
  /// Порядок — порядок полей в описании владельца.
  static List<
          ({String wireName, String property, String rowType, String? ownerFk})>
      tablePartsOf(NsgGenerator gen, NsgGenDataItem owner) {
    final owners = computeTableRowOwners(gen);
    final result = <({
      String wireName,
      String property,
      String rowType,
      String? ownerFk
    })>[];
    for (final f in owner.fields) {
      if (!_isList(f) || !_isEmittedField(f)) continue;
      final info = owners[f.referenceType];
      if (info == null ||
          info.typeName != owner.typeName ||
          info.collectionFieldName != f.name) {
        continue;
      }
      final row = gen.dataItems.values
          .firstWhere((d) => d.typeName == f.referenceType);
      final ownerFk = ownerFkFieldOf(row, owner.typeName)?.name;
      result.add((
        wireName: Misc.getDartName(f.name),
        property: f.name,
        rowType: row.typeName,
        ownerFk: ownerFk,
      ));
    }
    return result;
  }

  /// `Configurations/NsgTableParts.cs` (перезаписывается).
