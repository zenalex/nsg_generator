        '\n'
        '    /// <summary>Builds (Expression.Constant of List<E>, runtime-type of List<E>) from JSON array.</summary>\n'
        '    private static (Expression listConst, Type listType) BuildTypedList(JsonElement v, Type csType)\n'
        '    {\n'
        '        if (v.ValueKind != JsonValueKind.Array)\n'
        '            throw new ArgumentException(\$"In/NotIn expects JSON array value, got {v.ValueKind}");\n'
        '        var elementType = Nullable.GetUnderlyingType(csType) ?? csType;\n'
        '        var listType = typeof(List<>).MakeGenericType(elementType);\n'
        '        var list = (IList)Activator.CreateInstance(listType)!;\n'
