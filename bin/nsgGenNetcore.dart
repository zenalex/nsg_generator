        '\n'
        '    private static Expression BeginWithOp(Expression member, JsonElement v, Type csType, OpCtx ctx)\n'
        '        => LikeAtom(member, csType, ctx, ValueAsString(v), affix: LikeAffix.Prefix);\n'
        '\n'
