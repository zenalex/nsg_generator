  ///
  /// Семантика записи повторяет `NsgServerMetadataItem.ServerToNsgField`
  /// прежнего сервера:
  /// * табличная часть меняется, только если её ключ есть в присланном объекте;
  /// * без `newTableLogic` присланный массив — полный состав: чего в нём нет,
  ///   то удаляется;
  /// * с `newTableLogic` удаляются строки с `docState = 2`, остальные
  ///   досылаются выборочно и неприсланные остаются;
  /// * повтор идентификатора строки в массиве — отказ;
