        '        // op=26 (Compare nested) — НЕ в словаре; диспатч в BuildAtom до _ops lookup.\n'
        '    };\n'
        '\n'
        '    /// <summary>Защита от циклически коррумпированного wire-payload или DoS.\n'
        '    /// Реальные UI-фильтры почти всегда глубиной ≤ 3. При появлении legitimate\n'
        '    /// callsite с большей глубиной — пересмотр. TASK05 §5.5.</summary>\n'
        '    private const int MaxCompareDepth = 10;\n'
        '\n'
        '    /// <summary>Применяет NsgCompareDto к query. Возвращает либо исходный\n'
        '    /// query (если compare пуст), либо query.Where(predicate).</summary>\n'
        '    public IQueryable<T> Apply<T>(IQueryable<T> query, NsgCompareDto? compare, IModel efModel)\n'
        '    {\n'
        '        if (compare is null || compare.ParamList.Length == 0) return query;\n'
        '        if (!TypeFieldMapRegistry.ByType.TryGetValue(typeof(T), out var maps))\n'
        '            throw new InvalidOperationException(\$"No FieldMap for {typeof(T).Name}");\n'
        '        // Provider-detection: Postgres path uses EF.Functions.ILike;\n'
        '        // InMemory/non-relational path uses string.Contains/StartsWith/EndsWith.\n'
        '        // GetRelationalModel() требует финализированной модели — в unit-test fixture\n'
        '        // (`db.Model` сразу после конструкции DbContext) бросает InvalidOperationException;\n'
        '        // ловим и трактуем как non-relational (InMemory path).\n'
        '        bool isRel;\n'
        '        try { isRel = efModel.GetRelationalModel() != null; }\n'
        '        catch (InvalidOperationException ex)\n'
        '        {\n'
        '            // TASK06 §6.4 хвост W — теперь видно в логах.\n'
        '            _logger.LogWarning(ex, "LIKE-family fell back to InMemory path — IModel.GetRelationalModel() failed (model not finalized?) for type {EntityType}", typeof(T).Name);\n'
        '            isRel = false;\n'
        '        }\n'
        '        var ctx = new OpCtx(IsRelational: isRel, EfModel: efModel);\n'
        '        var param = Expression.Parameter(typeof(T), "x");\n'
        '        var body = BuildExpression(compare, param, typeof(T), maps, ctx, depth: 0);\n'
        '        if (body is null) return query;\n'
        '        var lambda = Expression.Lambda<Func<T, bool>>(body, param);\n'
        '        return query.Where(lambda);\n'
        '    }\n'
        '\n'
        '    private static Expression? BuildExpression(NsgCompareDto compare, ParameterExpression param, Type entityType, FieldMaps maps, OpCtx ctx, int depth)\n'
        '    {\n'
        '        if (depth > MaxCompareDepth)\n'
        '            throw new InvalidOperationException(\$"NsgCompare nesting too deep (max={MaxCompareDepth}): potential corruption or malicious payload");\n'
        '        var atoms = new List<Expression>();\n'
        '        foreach (var p in compare.ParamList)\n'
        '        {\n'
        '            atoms.Add(BuildAtom(p, param, entityType, maps, ctx, depth));\n'
        '        }\n'
        '        if (atoms.Count == 0) return null;\n'
        '        if (atoms.Count == 1) return atoms[0];\n'
        '        // LogicalOperator: 1 = AND, 2 = OR, anything else = AND (safe default).\n'
        '        var combine = compare.LogicalOperator == 2\n'
        '            ? new Func<Expression, Expression, Expression>(Expression.OrElse)\n'
        '            : new Func<Expression, Expression, Expression>(Expression.AndAlso);\n'
        '        return atoms.Aggregate(combine);\n'
        '    }\n'
        '\n'
        '    private static Expression BuildAtom(NsgCompareParamDto p, ParameterExpression param, Type entityType, FieldMaps maps, OpCtx ctx, int depth)\n'
        '    {\n'
        '        // 5.5: op=26 (Compare nested) — dispatch ДО dot-path / FieldMap-check.\n'
        '        // На Dart-клиенте диспатч по типу parameterValue (см. nsg_data_compare.dart:229-231);\n'
        '        // Name для op=26 ИГНОРИРУЕТСЯ (используется только в client-side toString).\n'
        '        if (p.ComparisonOperator == 26)\n'
        '        {\n'
        '            if (p.Nested is null)\n'
        '                throw new InvalidOperationException("Compare-operator (26) requires nested NsgCompare in Value (object), got " + p.Value.ValueKind);\n'
        '            // Ремарка B на §5.5: empty nested ParamList → true-предикат (no-op),\n'
        '            // симметрично top-level Apply.\n'
        '            if (p.Nested.ParamList.Length == 0)\n'
        '                return Expression.Constant(true);\n'
        '            var nested = BuildExpression(p.Nested, param, entityType, maps, ctx, depth + 1);\n'
        '            // BuildExpression возвращает null только если ParamList пуст — уже обработано выше.\n'
        '            return nested ?? Expression.Constant(true);\n'
        '        }\n'
        '        // 5.6.1: dot-path resolver. Wire-формат — camelCase + Id-суффикс на FK-сегментах\n'
        '        // (например "shopId.photoId.name" → x.Shop.Photo.Name). Резолвится через цепочку\n'
        '        // FieldMap → EF Core IModel nav-property → chained Expression.Property.\n'
        '        // NullGuard от резолвера — AND-цепочка `x.Nav != null && ...` для null-safety\n'
        '        // на InMemory LINQ (на Postgres+EF Core это no-op через LEFT JOIN).\n'
        '        Expression member;\n'
        '        Type csType;\n'
        '        Expression? nullGuard = null;\n'
        '        if (p.Name.Contains(\'.\'))\n'
        '        {\n'
        '            var (m, t, g) = DotPathResolver.Resolve(param, entityType, p.Name, ctx.EfModel);\n'
        '            member = m;\n'
        '            csType = t;\n'
        '            nullGuard = g;\n'
        '        }\n'
        '        else\n'
        '        {\n'
        '            if (!maps.WireToCSharp.TryGetValue(p.Name, out var csName))\n'
        '                throw new InvalidOperationException(\$"Wire field \\"{p.Name}\\" not in {entityType.Name}.FieldMap");\n'
        '            var prop = entityType.GetProperty(csName)\n'
        '                ?? throw new InvalidOperationException(\$"C# property {csName} not found on {entityType.Name}");\n'
        '            member = Expression.Property(param, prop);\n'
        '            csType = prop.PropertyType;\n'
        '        }\n'
        '        if (!_ops.TryGetValue(p.ComparisonOperator, out var emit))\n'
        '            throw new NotImplementedException(\$"operator {p.ComparisonOperator} (field \\"{p.Name}\\") not implemented; supported in 5.3-5.5: 1-22, 26 (type-predicates 23-25 deferred to FootballersDiary cutover)");\n'
        '        var atom = emit(member, p.Value, csType, ctx);\n'
        '        return nullGuard is null ? atom : Expression.AndAlso(nullGuard, atom);\n'
        '    }\n'
        '\n'
        '    // -------- binary operator emitters --------\n'
        '\n'
        '    private static Expression EqOp(Expression member, JsonElement v, Type csType, OpCtx _)\n'
