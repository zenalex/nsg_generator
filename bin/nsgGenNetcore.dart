        '        => Expression.Not(InOp(member, v, csType, ctx));\n'
        '\n'
        '    // -------- equality-or-empty operator emitters (TASK05 §5.5) --------\n'
        '\n'
        '    /// <summary>EqualOrEmpty: field == pv || field == null || (field == "" if string).\n'
        '    /// Type-conditional empty-string check (только для string/string?).\n'
        '    /// Guid.Empty НЕ проверяется (Dart-faithful, см. хвост X).</summary>\n'
        '    private static Expression EqualOrEmptyOp(Expression member, JsonElement v, Type csType, OpCtx _)\n'
        '    {\n'
        '        var eq     = Expression.Equal(member, ConstOf(v, csType));\n'
        '        var isNull = BuildNullCheck(member, csType);\n'
        '        Expression result = Expression.OrElse(eq, isNull);\n'
        '        var underlying = Nullable.GetUnderlyingType(csType) ?? csType;\n'
        '        if (underlying == typeof(string))\n'
        '        {\n'
        '            var isEmpty = Expression.Equal(member, Expression.Constant("", typeof(string)));\n'
        '            result = Expression.OrElse(result, isEmpty);\n'
        '        }\n'
        '        return result;\n'
        '    }\n'
        '\n'
        '    /// <summary>NotEqualOrEmpty = De Morgan: field != pv && field != null && (field != "" if string).\n'
        '    /// Семантически — «поле задано (не null, не пустая строка) И не равно искомому».</summary>\n'
        '    private static Expression NotEqualOrEmptyOp(Expression member, JsonElement v, Type csType, OpCtx _)\n'
        '    {\n'
        '        var neq     = Expression.NotEqual(member, ConstOf(v, csType));\n'
        '        var notNull = Expression.Not(BuildNullCheck(member, csType));\n'
        '        Expression result = Expression.AndAlso(neq, notNull);\n'
        '        var underlying = Nullable.GetUnderlyingType(csType) ?? csType;\n'
        '        if (underlying == typeof(string))\n'
        '        {\n'
        '            var notEmpty = Expression.NotEqual(member, Expression.Constant("", typeof(string)));\n'
        '            result = Expression.AndAlso(result, notEmpty);\n'
        '        }\n'
        '        return result;\n'
        '    }\n'
        '\n'
        '    /// <summary>Null-check для разных категорий типов:\n'
        '    /// - Nullable&lt;T&gt; (Guid?, int? etc.) или reference type (string) — `member == null`;\n'
        '    /// - non-nullable value type (Guid не-nullable etc.) — `Constant(false)` (никогда не null).</summary>\n'
        '    private static Expression BuildNullCheck(Expression member, Type csType)\n'
        '    {\n'
        '        if (Nullable.GetUnderlyingType(csType) != null || !csType.IsValueType)\n'
        '            return Expression.Equal(member, Expression.Constant(null, csType));\n'
        '        return Expression.Constant(false);\n'
        '    }\n'
        '\n'
