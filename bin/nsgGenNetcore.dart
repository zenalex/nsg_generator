        '        => Expression.Not(BeginWithOp(member, v, csType, ctx));\n'
        '\n'
        '    private static Expression EndWithOp(Expression member, JsonElement v, Type csType, OpCtx ctx)\n'
        '        => LikeAtom(member, csType, ctx, ValueAsString(v), affix: LikeAffix.Suffix);\n'
        '\n'
        '    private static Expression NotEndWithOp(Expression member, JsonElement v, Type csType, OpCtx ctx)\n'
        '        => Expression.Not(EndWithOp(member, v, csType, ctx));\n'
        '\n'
        '    private static Expression ContainOp(Expression member, JsonElement v, Type csType, OpCtx ctx)\n'
        '        => LikeAtom(member, csType, ctx, ValueAsString(v), affix: LikeAffix.Both);\n'
        '\n'
        '    private static Expression NotContainOp(Expression member, JsonElement v, Type csType, OpCtx ctx)\n'
        '        => Expression.Not(ContainOp(member, v, csType, ctx));\n'
        '\n'
        '    /// <summary>ContainWords: split по \' \' (как в Dart String.split(\' \')),\n'
        '    /// пустые слова отбрасываем, AND-chain `Contain` для каждого слова.\n'
        '    /// Match-в-любом-порядке (НЕ строим один pattern \'%w1%w2%\').</summary>\n'
        '    private static Expression ContainWordsOp(Expression member, JsonElement v, Type csType, OpCtx ctx)\n'
        '    {\n'
        '        EnsureStringType(csType, "ContainWords");\n'
        '        var raw = ValueAsString(v);\n'
        '        var words = raw.Split(\' \').Where(w => w.Length > 0).ToList();\n'
        '        if (words.Count == 0)\n'
        '        {\n'
        '            // Пустой value → ни одного предиката; вернём true (no-op),\n'
        '            // согласуется с клиентским every() по пустому списку.\n'
        '            return Expression.Constant(true);\n'
        '        }\n'
        '        Expression acc = LikeAtomFromString(member, csType, ctx, words[0], LikeAffix.Both);\n'
        '        for (int i = 1; i < words.Count; i++)\n'
        '        {\n'
        '            var w = LikeAtomFromString(member, csType, ctx, words[i], LikeAffix.Both);\n'
        '            acc = Expression.AndAlso(acc, w);\n'
        '        }\n'
        '        return acc;\n'
        '    }\n'
        '\n'
        '    /// <summary>NotContainWords = De Morgan «хотя бы одно слово отсутствует»\n'
        '    /// (буквальное !words.every на клиенте), НЕ «ни одно из слов не содержится».</summary>\n'
        '    private static Expression NotContainWordsOp(Expression member, JsonElement v, Type csType, OpCtx ctx)\n'
        '    {\n'
        '        var inner = ContainWordsOp(member, v, csType, ctx);\n'
        '        // Если inner — Constant(true) (пустой value), Not(true) = false — то есть\n'
        '        // на пустом value клиент возвращает !true = false. Симметрично.\n'
        '        return Expression.Not(inner);\n'
        '    }\n'
        '\n'
        '    // -------- LIKE helpers --------\n'
        '\n'
        '    private enum LikeAffix { Prefix, Suffix, Both }\n'
        '\n'
        '    private static Expression LikeAtom(Expression member, Type csType, OpCtx ctx, string raw, LikeAffix affix)\n'
        '    {\n'
        '        EnsureStringType(csType, AffixOpName(affix));\n'
        '        return LikeAtomFromString(member, csType, ctx, raw, affix);\n'
        '    }\n'
        '\n'
        '    private static Expression LikeAtomFromString(Expression member, Type csType, OpCtx ctx, string raw, LikeAffix affix)\n'
        '    {\n'
        '        if (ctx.IsRelational)\n'
        '        {\n'
        '            // Postgres path — EF.Functions.ILike(field, escaped-pattern).\n'
        '            // Escape `\\`, `%`, `_` в value (порядок важен — сначала `\\`).\n'
        '            var pattern = affix switch\n'
        '            {\n'
        '                LikeAffix.Prefix => EscapeLikeLiteral(raw) + "%",\n'
        '                LikeAffix.Suffix => "%" + EscapeLikeLiteral(raw),\n'
        '                LikeAffix.Both   => "%" + EscapeLikeLiteral(raw) + "%",\n'
        '                _ => throw new InvalidOperationException(),\n'
        '            };\n'
        '            return Expression.Call(\n'
        '                _ilikeMethod.Value,\n'
        '                Expression.Constant(EF.Functions),\n'
        '                member,\n'
        '                Expression.Constant(pattern));\n'
        '        }\n'
        '        // InMemory path — string.StartsWith/EndsWith/Contains с OrdinalIgnoreCase.\n'
        '        // Без эскейпинга — у строковых методов нет wildcards.\n'
        '        var methodName = affix switch\n'
        '        {\n'
        '            LikeAffix.Prefix => "StartsWith",\n'
        '            LikeAffix.Suffix => "EndsWith",\n'
        '            LikeAffix.Both   => "Contains",\n'
        '            _ => throw new InvalidOperationException(),\n'
        '        };\n'
        '        var mi = typeof(string).GetMethod(methodName, new[] { typeof(string), typeof(StringComparison) })\n'
        '            ?? throw new InvalidOperationException(\$"string.{methodName}(string, StringComparison) not found");\n'
        '        return Expression.Call(member, mi, Expression.Constant(raw), Expression.Constant(StringComparison.OrdinalIgnoreCase));\n'
        '    }\n'
        '\n'
        '    /// <summary>Эскейп литерала под Postgres LIKE/ILIKE: `\\`→`\\\\`, `%`→`\\%`, `_`→`\\_`.\n'
        '    /// Порядок важен — сначала `\\`, иначе двойное экранирование съест свежедобавленные.</summary>\n'
        '    private static string EscapeLikeLiteral(string raw)\n'
        '        => raw.Replace("\\\\", "\\\\\\\\").Replace("%", "\\\\%").Replace("_", "\\\\_");\n'
        '\n'
        '    private static string ValueAsString(JsonElement v)\n'
        '    {\n'
        '        if (v.ValueKind == JsonValueKind.String) return v.GetString() ?? "";\n'
        '        if (v.ValueKind == JsonValueKind.Null) return "";\n'
        '        // Толерантно — для number/bool возьмём RawText без кавычек.\n'
        '        return v.GetRawText().Trim(\'"\');\n'
        '    }\n'
        '\n'
        '    private static void EnsureStringType(Type csType, string opName)\n'
        '    {\n'
        '        var underlying = Nullable.GetUnderlyingType(csType) ?? csType;\n'
