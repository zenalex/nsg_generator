            await db.Database.MigrateAsync();
            log.LogInformation("База создана, миграции применены.");
            return;
        }

        var pending = (await db.Database.GetPendingMigrationsAsync()).ToList();
        if (pending.Count == 0) return;

        if (!migrateOnStartup)
            throw new InvalidOperationException(
                "Схема базы данных отстаёт от версии сборки: не применено миграций — "
                + pending.Count + " (" + string.Join(", ", pending) + "). "
                + "Сервер не начнёт обслуживание: на старой схеме запись прошла бы "
                + "успешно, но с потерей полей. Примените миграции запуском с аргументом "
                + "`--migrate` или включите " + MigrateOnStartupKey + " в конфигурации.");

        log.LogInformation("Схема отстаёт, применяются миграции ({Count}): {Names}",
            pending.Count, string.Join(", ", pending));
        await db.Database.MigrateAsync();
        log.LogInformation("Миграции применены, схема актуальна.");
    }
}
''';
