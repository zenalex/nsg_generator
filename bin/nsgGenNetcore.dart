        '\n'
        '    private static Expression GteOp(Expression member, JsonElement v, Type csType, OpCtx _)\n'
        '        => CompareOp(member, v, csType, isGt: true,  isEq: true);\n'
        '\n'
        '    private static Expression LtOp(Expression member, JsonElement v, Type csType, OpCtx _)\n'
        '        => CompareOp(member, v, csType, isGt: false, isEq: false);\n'
        '\n'
        '    private static Expression LteOp(Expression member, JsonElement v, Type csType, OpCtx _)\n'
        '        => CompareOp(member, v, csType, isGt: false, isEq: true);\n'
        '\n'
        '    /// <summary>Order comparison. For string uses string.Compare(...,Ordinal)\n'
        '    /// (Postgres/EF Core translate to "&gt;"; LINQ-to-Objects has no string operator).\n'
        '    /// For other comparable types — plain Expression.GreaterThan/LessThan.\n'
        '    /// На реальной Postgres collation-чувствителен — см. хвост T в TASK05.</summary>\n'
        '    private static Expression CompareOp(Expression member, JsonElement v, Type csType, bool isGt, bool isEq)\n'
        '    {\n'
        '        var underlying = Nullable.GetUnderlyingType(csType) ?? csType;\n'
        '        if (underlying == typeof(string))\n'
        '        {\n'
        '            var cmp = typeof(string).GetMethod("Compare", new[] { typeof(string), typeof(string), typeof(StringComparison) })!;\n'
        '            var call = Expression.Call(cmp, member, ConstOf(v, csType), Expression.Constant(StringComparison.Ordinal));\n'
        '            var zero = Expression.Constant(0);\n'
        '            return isGt\n'
        '                ? (isEq ? Expression.GreaterThanOrEqual(call, zero) : Expression.GreaterThan(call, zero))\n'
        '                : (isEq ? Expression.LessThanOrEqual(call, zero)    : Expression.LessThan(call, zero));\n'
        '        }\n'
        '        var c = ConstOf(v, csType);\n'
        '        return isGt\n'
        '            ? (isEq ? Expression.GreaterThanOrEqual(member, c) : Expression.GreaterThan(member, c))\n'
        '            : (isEq ? Expression.LessThanOrEqual(member, c)    : Expression.LessThan(member, c));\n'
        '    }\n'
        '\n'
        '    private static Expression InOp(Expression member, JsonElement v, Type csType, OpCtx _)\n'
        '    {\n'
        '        var (listConst, listType) = BuildTypedList(v, csType);\n'
        '        var elementType = Nullable.GetUnderlyingType(csType) ?? csType;\n'
        '        var contains = listType.GetMethod("Contains", new[] { elementType })\n'
        '            ?? throw new InvalidOperationException(\$"Contains not found on {listType}");\n'
        '        // Ссылка — Guid?, список — Guid: поле приводится к типу элемента\n'
        '        // (EF переводит это в обычное сравнение колонки; null в список не входит).\n'
        '        var arg = member.Type == elementType ? member : Expression.Convert(member, elementType);\n'
        '        return Expression.Call(listConst, contains, arg);\n'
        '    }\n'
