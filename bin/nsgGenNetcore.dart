    return '''
// <auto-generated>
//   This file is generated by nsg_generator (one-shot). Manual edits are preserved.
// </auto-generated>
#nullable enable
using System;
using System.Security.Cryptography;
using System.Text;

namespace $ns.Auth;

/// <summary>Одноразовый код доступа: выдача, хеширование, сверка.</summary>
public static class NsgAccessCode
{
    /// Алфавит без визуально неразличимых знаков: нет 0/O, 1/I/L.
    /// 32 знака — ровно 5 бит на знак, что делает подсчёт энтропии точным.
    private const string Alphabet = "23456789ABCDEFGHJKMNPQRSTUVWXYZ#";

    /// <summary>Новый код. По умолчанию 10 знаков = 50 бит энтропии.</summary>
    public static string Generate(int length = 10)
    {
        if (length < 8)
            throw new ArgumentOutOfRangeException(nameof(length),
                "код короче 8 знаков даёт меньше 40 бит энтропии и подбирается");
        var chars = new char[length];
        Span<byte> buf = stackalloc byte[length];
        RandomNumberGenerator.Fill(buf);
        for (var i = 0; i < length; i++) chars[i] = Alphabet[buf[i] % Alphabet.Length];
        return new string(chars);
    }

    /// <summary>Хеш для хранения и поиска. Соль на запись невозможна: поиск
    /// идёт по хешу. Её отсутствие безопасно именно потому, что код случаен —
    /// словарной атаки, от которой защищает соль, здесь не существует.
    /// Общий секрет (pepper) добавляется из конфигурации.</summary>
    public static string Hash(string code, string pepper)
    {
        var bytes = Encoding.UTF8.GetBytes(pepper + code.Trim().ToUpperInvariant());
        return Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();
    }

    /// <summary>Сверка за постоянное время: время ответа не должно зависеть
    /// от того, сколько знаков совпало.</summary>
    public static bool Verify(string code, string pepper, string storedHash)
    {
        var a = Encoding.UTF8.GetBytes(Hash(code, pepper));
        var b = Encoding.UTF8.GetBytes(storedHash);
        return CryptographicOperations.FixedTimeEquals(a, b);
    }
}
''';
